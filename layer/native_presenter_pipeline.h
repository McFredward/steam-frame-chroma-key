#pragma once

// Completion-scoped pipeline creation primitive. This header installs no hook,
// selects no native pipeline and authorizes no device execution. An eventual
// caller must obtain the exact definitions from THIS native creation callback,
// while Vulkan's original dependency handles and CI remain valid. Historical
// recipes, numeric handle equality or a former successful capture are not leases.
#include "pixel_ssbo_clone_contract.h"

namespace frame_native_presenter {
namespace definitions = frame_pixel_ssbo_clone;
constexpr std::size_t MaximumArtifactBytes=64u*1024u;
// Deterministic private guarded fragment; independently executed GPU evidence
// is recorded separately and does not turn this primitive into a runtime hook.
constexpr const char* GuardedFragmentSha256="0aaf356d3789473cd32ff0d60cf5971bc1473813241657877db5c147bb1d4364";
constexpr std::size_t GuardedFragmentBytes=18416;

enum class Reason : std::uint8_t {
    None,Artifact,ApiVersion,Original,Identity,Interface,Graphics,Dispatch,NativeCreation,
    ShaderCreation,PipelineCreation,UnexpectedHandle
};
enum class GraphicsGate : std::uint8_t {
    None,Contract,Blend,Dynamic,ColorWrite,Attachment,Format,Multisample,Stages
};
struct Result {
    Reason reason=Reason::None;
    VkResult replacementResult=VK_SUCCESS;
    bool replaced=false;
    GraphicsGate graphicsGate=GraphicsGate::None;
    VkFormat attachmentFormat=VK_FORMAT_UNDEFINED;
    VkDynamicState unsupportedDynamic=VK_DYNAMIC_STATE_MAX_ENUM;
};

// Private generated bytes are copied and hashed during cold preparation.
// A caller digest never admits arbitrary replacement code. The production pin
// belongs here; the Valve original and generated body must not be distributed.
class Fragment {
public:
    bool prepare(const std::uint32_t* words,std::size_t bytes) noexcept {
        bytes_=0;
        if(!words||!GuardedFragmentBytes||bytes!=GuardedFragmentBytes||bytes>MaximumArtifactBytes||bytes%4)
            return false;
        std::memcpy(words_.data(),words,bytes);
        frame_receiver::Sha256 hash;hash.update(words_.data(),bytes);
        if(!definitions::digestMatches(hash.finish(),GuardedFragmentSha256))return false;
        bytes_=bytes;return true;
    }
    bool ready() const noexcept{return bytes_!=0;}
    const std::uint32_t* words() const noexcept{return ready()?words_.data():nullptr;}
    std::size_t bytes() const noexcept{return bytes_;}
private:
    std::array<std::uint32_t,MaximumArtifactBytes/4> words_{};
    std::size_t bytes_=0;
};

struct Dispatch {
    PFN_vkCreateShaderModule createShader=nullptr;
    PFN_vkDestroyShaderModule destroyShader=nullptr;
    PFN_vkCreateGraphicsPipelines createPipeline=nullptr;
    PFN_vkDestroyPipeline destroyPipeline=nullptr;
};

// Retains every original CI pointer/value except pStages, whose two entries are
// copied and whose single fragment-module handle is replaced. Native descriptors,
// pipeline layout, render pass, vertex stage, viewport, dynamic state, blend,
// push constants and draw arguments are never rebound or copied into new objects.
// The caller already has a successfully created original pipeline. Any rejected
// admission or replacement failure keeps that pipeline and its result untouched.
inline Result replaceCompletedPipeline(VkDevice device,VkPipelineCache cache,std::uint32_t negotiatedApiVersion,
        VkResult originalResult,const VkGraphicsPipelineCreateInfo& original,const VkAllocationCallbacks* allocator,
        VkPipeline& completed,const definitions::Recipe& currentDefinitions,
        const Fragment& fragment,const Dispatch& dispatch) noexcept {
    if(!fragment.ready())return {Reason::Artifact};
    // The generated marker requires SPIR-V1.1; only the actual negotiated API
    // supplies this core guarantee, never a physical-device maximum or PFN.
    if(VK_API_VERSION_VARIANT(negotiatedApiVersion)||negotiatedApiVersion<VK_API_VERSION_1_1)return {Reason::ApiVersion};
    if(originalResult!=VK_SUCCESS||!device||!completed||!currentDefinitions.definitionComplete)return {Reason::Original};
    const auto& p=currentDefinitions.provenance;
    const auto value=definitions::handle(device);
    for(const auto& identity:p)
        if(identity.device!=value||!identity.value||!identity.generation)return {Reason::Identity};
    if(p[5].value!=definitions::handle(completed)||p[1].value!=definitions::handle(original.layout)||
       p[2].value!=definitions::handle(original.renderPass))return {Reason::Identity};
    // Exact source pins are checked again, rather than trusting recipe booleans.
    definitions::ShaderDefinition vs,ps;definitions::Refusal why;
    VkShaderModuleCreateInfo source{};source.sType=VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO;
    source.codeSize=currentDefinitions.vertex.bytes;source.pCode=currentDefinitions.vertex.words.data();
    if(!definitions::captureShader(source,definitions::ShaderRole::Vertex,vs,why))return {Reason::Original};
    source.codeSize=currentDefinitions.fragment.bytes;source.pCode=currentDefinitions.fragment.words.data();
    if(!definitions::captureShader(source,definitions::ShaderRole::Fragment,ps,why))return {Reason::Original};
    const auto& set=currentDefinitions.set0;
    if(!set.complete||set.pendingCount1||set.count>definitions::MaxBindings||!currentDefinitions.layout.complete||
       currentDefinitions.renderPass.subpassCount>definitions::MaxSubpasses)return {Reason::Interface};
    bool image=false,sampler=false;
    for(unsigned i=0;i<set.count;++i){const auto& binding=set.bindings[i];
        if(binding.binding==9)image=binding.descriptorType==VK_DESCRIPTOR_TYPE_SAMPLED_IMAGE&&
            (binding.descriptorCount==1||binding.descriptorCount==3)&&
            (binding.stageFlags&VK_SHADER_STAGE_FRAGMENT_BIT);
        if(binding.binding==25)sampler=binding.descriptorType==VK_DESCRIPTOR_TYPE_SAMPLER&&
            binding.descriptorCount==1&&(binding.stageFlags&VK_SHADER_STAGE_FRAGMENT_BIT);
    }
    if(!image||!sampler)return {Reason::Interface};
    VkShaderModule vertex{},oldFragment{};
    std::memcpy(&vertex,&p[3].value,sizeof(vertex));
    std::memcpy(&oldFragment,&p[4].value,sizeof(oldFragment));
    definitions::GraphicsDefinition checked;
    // Cold refusal detail only. These values never widen admission or identify
    // a source frame; they make a rejected first visible trial diagnosable.
    VkFormat observedFormat=VK_FORMAT_UNDEFINED;
    const auto* observedSubpass=currentDefinitions.renderPass.subpass(original.subpass);
    if(observedSubpass&&observedSubpass->colorCount==1){
        const auto index=observedSubpass->colors[0].attachment;
        if(index!=VK_ATTACHMENT_UNUSED&&index<currentDefinitions.renderPass.attachmentCount&&
           currentDefinitions.renderPass.attachmentCount<=definitions::MaxAttachments)
            observedFormat=currentDefinitions.renderPass.attachments[index].format;
    }
    const auto graphicsRefusal=[&](GraphicsGate gate,VkDynamicState dynamic=VK_DYNAMIC_STATE_MAX_ENUM){
        return Result{Reason::Graphics,VK_SUCCESS,false,gate,observedFormat,dynamic};
    };
    if(!definitions::captureGraphics(original,original.layout,original.renderPass,vertex,oldFragment,
            currentDefinitions.renderPass,checked,why,&currentDefinitions.feature))return graphicsRefusal(GraphicsGate::Contract);
    // Only an unblended RGBA target admits this premultiplied contribution.
    // Other original routes remain opaque, even if their shader pins coincide.
    const auto* subpass=currentDefinitions.renderPass.subpass(original.subpass);
    if(!subpass||subpass->colorCount!=1||!checked.hasColors||checked.blend.attachmentCount!=1||
       checked.colors[0].blendEnable||checked.colors[0].colorWriteMask!=0xf||checked.blend.logicOpEnable)
        return graphicsRefusal(GraphicsGate::Blend);
    // Keep the first prototype independent of dynamically selected write/blend
    // rules. Unknown output state must never turn stock opacity into a guess.
    for(unsigned i=0;i<checked.dynamic.dynamicStateCount;++i)
        if(checked.dynamics[i]!=VK_DYNAMIC_STATE_VIEWPORT&&checked.dynamics[i]!=VK_DYNAMIC_STATE_SCISSOR&&
           checked.dynamics[i]!=VK_DYNAMIC_STATE_LINE_WIDTH&&checked.dynamics[i]!=VK_DYNAMIC_STATE_BLEND_CONSTANTS&&
           checked.dynamics[i]!=VK_DYNAMIC_STATE_DEPTH_BOUNDS&&checked.dynamics[i]!=VK_DYNAMIC_STATE_STENCIL_COMPARE_MASK&&
           checked.dynamics[i]!=VK_DYNAMIC_STATE_STENCIL_WRITE_MASK&&checked.dynamics[i]!=VK_DYNAMIC_STATE_STENCIL_REFERENCE&&
           checked.dynamics[i]!=VK_DYNAMIC_STATE_STENCIL_TEST_ENABLE&&checked.dynamics[i]!=VK_DYNAMIC_STATE_STENCIL_OP&&
           checked.dynamics[i]!=VK_DYNAMIC_STATE_SAMPLE_LOCATIONS_EXT&&checked.dynamics[i]!=VK_DYNAMIC_STATE_SAMPLE_LOCATIONS_ENABLE_EXT)
            return graphicsRefusal(GraphicsGate::Dynamic,checked.dynamics[i]);
    if(checked.hasColorWrites&&checked.colorWrites[0]!=VK_TRUE)return graphicsRefusal(GraphicsGate::ColorWrite);
    const auto attachment=subpass->colors[0].attachment;
    if(attachment==VK_ATTACHMENT_UNUSED||attachment>=currentDefinitions.renderPass.attachmentCount||
       currentDefinitions.renderPass.attachmentCount>definitions::MaxAttachments)return graphicsRefusal(GraphicsGate::Attachment);
    switch(currentDefinitions.renderPass.attachments[attachment].format){
    case VK_FORMAT_R8G8B8A8_UNORM:case VK_FORMAT_R8G8B8A8_SRGB:
    case VK_FORMAT_B8G8R8A8_UNORM:case VK_FORMAT_B8G8R8A8_SRGB:
    case VK_FORMAT_R16G16B16A16_SFLOAT:case VK_FORMAT_R32G32B32A32_SFLOAT:break;
    default:return graphicsRefusal(GraphicsGate::Format);
    }
    if(!checked.hasMultisample||checked.multisample.alphaToOneEnable||checked.multisample.alphaToCoverageEnable||
       original.pMultisampleState->pNext)return graphicsRefusal(GraphicsGate::Multisample);
    if(!dispatch.createShader||!dispatch.destroyShader||!dispatch.createPipeline||!dispatch.destroyPipeline)
        return {Reason::Dispatch};
    VkShaderModuleCreateInfo ci{};ci.sType=VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO;
    ci.pCode=fragment.words();ci.codeSize=fragment.bytes();
    VkShaderModule owned=VK_NULL_HANDLE;
    auto result=dispatch.createShader(device,&ci,allocator,&owned);
    // Failed shader output is undefined, never destroy a garbage returned value.
    if(result!=VK_SUCCESS)return {Reason::ShaderCreation,result};
    if(!owned)return {Reason::UnexpectedHandle};
    auto replacement=original;
    std::array<VkPipelineShaderStageCreateInfo,2> stages{{original.pStages[0],original.pStages[1]}};
    unsigned changed=0;
    for(auto& stage:stages)if(stage.stage==VK_SHADER_STAGE_FRAGMENT_BIT){stage.module=owned;++changed;}
    if(changed!=1){dispatch.destroyShader(device,owned,allocator);return graphicsRefusal(GraphicsGate::Stages);}
    replacement.pStages=stages.data();
    VkPipeline newPipeline=VK_NULL_HANDLE;
    result=dispatch.createPipeline(device,cache,1,&replacement,allocator,&newPipeline);
    // The shader can be destroyed after synchronous pipeline creation; the
    // pipeline retains its compiled code (Vulkan vkDestroyShaderModule).
    dispatch.destroyShader(device,owned,allocator);
    if(result!=VK_SUCCESS||!newPipeline){
        // Partial pipeline success is a defined owned handle, unlike failed
        // vkCreateShaderModule output. Do not leak it on an error result.
        if(newPipeline)dispatch.destroyPipeline(device,newPipeline,allocator);
        return {Reason::PipelineCreation,result};
    }
    if(newPipeline==completed)return {Reason::UnexpectedHandle}; // Valid native creation must return a distinct live object.
    const auto previous=completed;
    completed=newPipeline;
    dispatch.destroyPipeline(device,previous,allocator);
    return {Reason::None,VK_SUCCESS,true};
}
} // namespace frame_native_presenter
